//! Shopping v2 ops with the client offline outbox.
//!
//! Server (`Lucina/src/grocery/shopping.js::applyShoppingOps`, Rust port
//! `lucina-grocery/src/lib.rs`, branch `lucina-rs`; contract
//! `docs/shopping-v2.md`): one transaction per batch under the list row lock;
//! op ids already in `grocery.shopping_ops` are duplicates; a stale
//! `expectedRevision` is a 409 only when a fresh op conflicts (its row
//! changed after that revision, or an add would overwrite fields); nothing
//! is recorded on a 409; ops on an unknown row are rejected with a receipt;
//! a removed row stays removed; one active row per (list, object) because an
//! add merges into the active row of its object.
//!
//! Client (`web/src/state/shopping.ts::flushOutbox`, `lib/shoppingOps.ts::
//! rebaseOps`; the item-objects version on branch `shopping-items`): every
//! queued op of a list goes out in one batch with the cached revision; a
//! network error keeps the outbox (same op ids); 200 drops every sent op
//! (applied, duplicate or rejected) and remaps optimistic row ids by object;
//! 409 refetches and rebases the queued ops on the fresh rows with new op
//! ids, dropping the ones that change nothing.

use stateright::{Model, Property};

use crate::{set_has, set_insert, Case, Expect};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum RowId {
    /// Generated by the server (`gen_random_uuid()`).
    Server(u8),
    /// A client's optimistic row id (`rowId`, a UUID).
    Client(u8, u8),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum St {
    Needed,
    Recent,
    Removed,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Row {
    pub id: RowId,
    pub obj: u8,
    pub st: St,
    pub spec: bool,
    pub rev: u8,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Kind {
    /// add {itemId: object, rowId, spec?}
    Add(u8, RowId, bool),
    Purchase(RowId),
    Need(RowId),
    Remove(RowId),
}

impl Kind {
    fn target(self) -> Option<RowId> {
        match self {
            Kind::Add(..) => None,
            Kind::Purchase(r) | Kind::Need(r) | Kind::Remove(r) => Some(r),
        }
    }
    fn retarget(self, from: RowId, to: RowId) -> Kind {
        let f = |r: RowId| if r == from { to } else { r };
        match self {
            Kind::Add(o, r, s) => Kind::Add(o, f(r), s),
            Kind::Purchase(r) => Kind::Purchase(f(r)),
            Kind::Need(r) => Kind::Need(f(r)),
            Kind::Remove(r) => Kind::Remove(f(r)),
        }
    }
}

/// One user intent (client, n): survives rebases, unlike the op id.
pub type Intent = (u8, u8);
/// (client, counter)
pub type OpId = (u8, u8);

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Op {
    pub id: OpId,
    pub intent: Intent,
    pub kind: Kind,
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum Resp {
    Ok {
        revision: u8,
        rows: Vec<Row>,
        applied: Vec<OpId>,
        duplicates: Vec<OpId>,
        rejected: Vec<OpId>,
    },
    Conflict {
        duplicates: Vec<OpId>,
    },
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Client {
    pub outbox: Vec<Op>,
    pub base_rev: u8,
    pub base: Vec<Row>,
    /// Sent batch and, once the server answered, its response.
    pub inflight: Option<(Vec<Op>, Option<Resp>)>,
    pub next_op: u8,
    /// Index of the next scripted user intent.
    pub script_pos: u8,
    pub conflicts: u8,
    /// remapIds: optimistic row → server row, as the UI shows it afterwards.
    pub alias: Vec<(RowId, RowId)>,
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct State {
    pub revision: u8,
    pub rows: Vec<Row>,
    pub next_row: u8,
    pub receipts: Vec<OpId>,
    /// How many times each intent changed the server (applied, not a no-op merge).
    pub applied: Vec<(Intent, u8)>,
    pub clients: Vec<Client>,
    /// Intents whose op was dropped from an outbox as rejected (never applied).
    pub silently_dropped: Vec<Intent>,
    /// Intents acknowledged (200: applied or duplicate).
    pub acked: Vec<Intent>,
    pub ever_removed: Vec<RowId>,
    pub resurrected: bool,
    pub drops_left: u8,
    /// Fix S2: server-side rowId aliases (a merge records rowId → that row).
    pub aliases: Vec<(RowId, RowId)>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Action {
    /// The user does the next scripted thing on this client.
    User(u8),
    Send(u8),
    /// The server runs the batch (one transaction).
    Serve(u8),
    /// The response reaches the client.
    Receive(u8),
    /// The connection fails: before or after the server ran the batch.
    Lose(u8),
}

/// A user step: (kind template). `RowId::Client(c, k)` in a template is the
/// client's own optimistic row `k`; `RowId::Server(0)` is the seeded row.
#[derive(Clone, Debug)]
pub struct Shopping {
    pub scripts: Vec<Vec<Kind>>,
    /// Rows on the list at the start (both clients have fetched them).
    pub seed: Vec<Row>,
    pub drops: u8,
    pub max_conflict_retries: u8,
    /// Fix S1: the 409 body lists the batch's duplicate op ids
    /// (`duplicates` is computed before the conflict check) and the client
    /// drops those ops before rebasing.
    pub fix_dups_in_409: bool,
    /// Fix S2: the server uses the client's `rowId` (a fresh UUID) as the
    /// new row's id, like `web/mock/shopping-v2.mjs` already does, and when
    /// the add merges into an existing row it records `rowId → row` so later
    /// ops (same batch or a retry) that name the optimistic row still land.
    pub fix_client_row_ids: bool,
}

/// `applyOne`; `None` = rejected (`item_not_found`). Returns whether the
/// state changed (a merge into an identical row changes nothing).
fn apply(rows: &mut Vec<Row>, kind: Kind, rev: u8, new_id: RowId) -> Option<bool> {
    let before = rows.clone();
    match kind {
        Kind::Add(obj, _, spec) => {
            if let Some(r) = rows
                .iter_mut()
                .find(|r| r.obj == obj && r.st != St::Removed)
            {
                // Re-adding moves a recent item back to needed; one active row per object.
                r.st = St::Needed;
                r.spec |= spec;
                r.rev = rev;
            } else {
                rows.push(Row {
                    id: new_id,
                    obj,
                    st: St::Needed,
                    spec,
                    rev,
                });
            }
        }
        Kind::Purchase(t) | Kind::Need(t) | Kind::Remove(t) => {
            let r = rows.iter_mut().find(|r| r.id == t)?;
            // Deleted stays deleted: later ops on a removed row change nothing.
            if r.st != St::Removed {
                r.st = match kind {
                    Kind::Purchase(_) => St::Recent,
                    Kind::Need(_) => St::Needed,
                    _ => St::Removed,
                };
                r.rev = rev;
            }
        }
    }
    let changed = rows
        .iter()
        .map(|r| (r.id, r.obj, r.st, r.spec))
        .ne(before.iter().map(|r| (r.id, r.obj, r.st, r.spec)));
    Some(changed)
}

impl Shopping {
    fn client_row(c: u8, k: u8) -> RowId {
        RowId::Client(c, k)
    }

    fn serve(&self, s: &mut State, c: u8) -> Resp {
        let (batch, _) = s.clients[c as usize].inflight.clone().expect("inflight");
        let expected = s.clients[c as usize].base_rev;
        let mut duplicates = Vec::new();
        let mut fresh = Vec::new();
        let resolve = |aliases: &[(RowId, RowId)], k: Kind| -> Kind {
            match k.target() {
                Some(t) => match aliases.iter().find(|(a, _)| *a == t) {
                    Some((_, to)) => k.retarget(t, *to),
                    None => k,
                },
                None => k,
            }
        };
        for op in &batch {
            if set_has(&s.receipts, &op.id) || fresh.iter().any(|f: &Op| f.id == op.id) {
                duplicates.push(op.id);
            } else {
                fresh.push(*op);
            }
        }
        if expected < s.revision {
            let conflicting = fresh.iter().any(|op| {
                let row = match resolve(&s.aliases, op.kind) {
                    Kind::Add(obj, _, true) => {
                        s.rows.iter().find(|r| r.obj == obj && r.st != St::Removed)
                    }
                    Kind::Add(..) => None,
                    k => s.rows.iter().find(|r| Some(r.id) == k.target()),
                };
                row.is_some_and(|r| r.rev > expected)
            });
            if conflicting {
                return Resp::Conflict {
                    duplicates: if self.fix_dups_in_409 {
                        duplicates
                    } else {
                        Vec::new()
                    },
                };
            }
        }
        let rev = s.revision + 1;
        let mut applied = Vec::new();
        let mut rejected = Vec::new();
        for op in fresh {
            let new_id = match op.kind {
                Kind::Add(_, RowId::Client(a, b), _)
                    if self.fix_client_row_ids
                        && !s.rows.iter().any(|r| r.id == RowId::Client(a, b)) =>
                {
                    RowId::Client(a, b)
                }
                _ => RowId::Server(s.next_row),
            };
            let before_len = s.rows.len();
            let kind = resolve(&s.aliases, op.kind);
            if self.fix_client_row_ids {
                if let Kind::Add(obj, rid @ RowId::Client(..), _) = kind {
                    if let Some(r) = s.rows.iter().find(|r| r.obj == obj && r.st != St::Removed) {
                        if r.id != rid && !s.aliases.iter().any(|(a, _)| *a == rid) {
                            s.aliases.push((rid, r.id));
                            s.aliases.sort();
                        }
                    }
                }
            }
            match apply(&mut s.rows, kind, rev, new_id) {
                None => rejected.push(op.id),
                Some(changed) => {
                    if s.rows.len() > before_len && matches!(new_id, RowId::Server(_)) {
                        s.next_row += 1;
                    }
                    applied.push(op.id);
                    if changed {
                        match s.applied.iter_mut().find(|(i, _)| *i == op.intent) {
                            Some((_, n)) => *n += 1,
                            None => {
                                s.applied.push((op.intent, 1));
                                s.applied.sort();
                            }
                        }
                    }
                }
            }
            set_insert(&mut s.receipts, op.id);
        }
        for r in &s.rows {
            if r.st == St::Removed {
                set_insert(&mut s.ever_removed, r.id);
            } else if set_has(&s.ever_removed, &r.id) {
                s.resurrected = true;
            }
        }
        if !applied.is_empty() {
            s.revision = rev;
        }
        Resp::Ok {
            revision: s.revision,
            rows: s.rows.clone(),
            applied,
            duplicates,
            rejected,
        }
    }

    fn receive(&self, s: &mut State, c: u8) {
        let (batch, resp) = s.clients[c as usize].inflight.take().expect("inflight");
        let resp = resp.expect("answered");
        match resp {
            Resp::Ok {
                revision,
                rows,
                applied,
                duplicates,
                rejected,
            } => {
                let cl = &mut s.clients[c as usize];
                let sent: Vec<OpId> = batch.iter().map(|o| o.id).collect();
                cl.outbox.retain(|o| !sent.contains(&o.id));
                // remapIds: an add's optimistic row → the server row of its object.
                for op in &batch {
                    if let Kind::Add(obj, rid, _) = op.kind {
                        if rows.iter().any(|r| r.id == rid) {
                            continue;
                        }
                        if let Some(m) = rows.iter().find(|r| r.obj == obj && r.st != St::Removed) {
                            let to = m.id;
                            for q in cl.outbox.iter_mut() {
                                q.kind = q.kind.retarget(rid, to);
                            }
                            cl.alias.push((rid, to));
                        }
                    }
                }
                if revision >= cl.base_rev {
                    cl.base_rev = revision;
                    cl.base = rows;
                }
                cl.conflicts = 0;
                for op in &batch {
                    if rejected.contains(&op.id) {
                        set_insert(&mut s.silently_dropped, op.intent);
                    }
                    if applied.contains(&op.id) || duplicates.contains(&op.id) {
                        set_insert(&mut s.acked, op.intent);
                    }
                }
            }
            Resp::Conflict { duplicates } => {
                let fresh_rev = s.revision;
                let fresh = s.rows.clone();
                let cl = &mut s.clients[c as usize];
                cl.conflicts += 1;
                cl.base_rev = fresh_rev;
                cl.base = fresh.clone();
                if cl.conflicts > self.max_conflict_retries {
                    // Gives up visibly (actionError): not counted as silent.
                    cl.outbox.clear();
                    return;
                }
                cl.outbox.retain(|o| !duplicates.contains(&o.id));
                // rebaseOps
                let mut items = fresh;
                let mut out = Vec::new();
                for op in cl.outbox.clone() {
                    if let Some(t) = op.kind.target() {
                        if !items.iter().any(|r| r.id == t && r.st != St::Removed) {
                            continue;
                        }
                    }
                    let mut next = op;
                    next.id = (c, cl.next_op);
                    let new_id = match op.kind {
                        Kind::Add(_, rid, _) => rid,
                        _ => RowId::Server(255),
                    };
                    match apply(&mut items, next.kind, 0, new_id) {
                        Some(true) => {
                            cl.next_op += 1;
                            out.push(next);
                        }
                        _ => continue,
                    }
                }
                cl.outbox = out;
            }
        }
    }
}

impl Model for Shopping {
    type State = State;
    type Action = Action;

    fn init_states(&self) -> Vec<State> {
        let clients = (0..self.scripts.len())
            .map(|_| Client {
                outbox: Vec::new(),
                base_rev: 0,
                base: self.seed.clone(),
                inflight: None,
                next_op: 0,
                script_pos: 0,
                conflicts: 0,
                alias: Vec::new(),
            })
            .collect();
        vec![State {
            revision: 0,
            rows: self.seed.clone(),
            next_row: 1,
            receipts: Vec::new(),
            applied: Vec::new(),
            clients,
            silently_dropped: Vec::new(),
            acked: Vec::new(),
            ever_removed: Vec::new(),
            resurrected: false,
            drops_left: self.drops,
            aliases: Vec::new(),
        }]
    }

    fn actions(&self, s: &State, a: &mut Vec<Action>) {
        for (i, cl) in s.clients.iter().enumerate() {
            let c = i as u8;
            if (cl.script_pos as usize) < self.scripts[i].len() {
                a.push(Action::User(c));
            }
            match &cl.inflight {
                None if !cl.outbox.is_empty() => a.push(Action::Send(c)),
                None => {}
                Some((_, None)) => {
                    a.push(Action::Serve(c));
                    if s.drops_left > 0 {
                        a.push(Action::Lose(c));
                    }
                }
                Some((_, Some(_))) => {
                    a.push(Action::Receive(c));
                    if s.drops_left > 0 {
                        a.push(Action::Lose(c));
                    }
                }
            }
        }
    }

    fn next_state(&self, last: &State, action: Action) -> Option<State> {
        let mut s = last.clone();
        match action {
            Action::User(c) => {
                let cl = &mut s.clients[c as usize];
                let k = cl.script_pos;
                let mut kind = self.scripts[c as usize][k as usize];
                // Templates name the client's own rows as Client(_, k).
                kind = match kind {
                    Kind::Add(o, RowId::Client(_, k), sp) => {
                        Kind::Add(o, Self::client_row(c, k), sp)
                    }
                    Kind::Purchase(RowId::Client(_, k)) => Kind::Purchase(Self::client_row(c, k)),
                    Kind::Need(RowId::Client(_, k)) => Kind::Need(Self::client_row(c, k)),
                    Kind::Remove(RowId::Client(_, k)) => Kind::Remove(Self::client_row(c, k)),
                    other => other,
                };
                // The UI names a row the way the client knows it now.
                if let Some(t) = kind.target() {
                    if let Some((_, to)) = cl.alias.iter().find(|(a, _)| *a == t) {
                        kind = kind.retarget(t, *to);
                    }
                }
                let op = Op {
                    id: (c, cl.next_op),
                    intent: (c, k),
                    kind,
                };
                cl.next_op += 1;
                cl.script_pos += 1;
                cl.outbox.push(op);
            }
            Action::Send(c) => {
                let cl = &mut s.clients[c as usize];
                cl.inflight = Some((cl.outbox.clone(), None));
            }
            Action::Serve(c) => {
                let resp = self.serve(&mut s, c);
                if let Some((_, r)) = s.clients[c as usize].inflight.as_mut() {
                    *r = Some(resp);
                }
            }
            Action::Receive(c) => self.receive(&mut s, c),
            Action::Lose(c) => {
                // Transient: the outbox stays as it is and is retried later.
                s.drops_left -= 1;
                s.clients[c as usize].inflight = None;
            }
        }
        Some(s)
    }

    fn properties(&self) -> Vec<Property<Self>> {
        vec![
            Property::always("no_duplicate_application", |_, s: &State| {
                s.applied.iter().all(|(_, n)| *n <= 1)
            }),
            Property::always("acked_applied_exactly_once", |_, s: &State| {
                s.acked
                    .iter()
                    .all(|i| s.applied.iter().find(|(x, _)| x == i).map_or(0, |p| p.1) <= 1)
            }),
            Property::always("no_silent_drop", |_, s: &State| {
                s.silently_dropped.is_empty()
            }),
            Property::always("deleted_stays_deleted", |_, s: &State| !s.resurrected),
            Property::always("one_active_row_per_object", |_, s: &State| {
                let mut objs: Vec<u8> = s
                    .rows
                    .iter()
                    .filter(|r| r.st != St::Removed)
                    .map(|r| r.obj)
                    .collect();
                let n = objs.len();
                objs.sort();
                objs.dedup();
                objs.len() == n
            }),
            Property::always("clients_converge", |m: &Shopping, s: &State| {
                // Quiescent: scripts done, outboxes empty, nothing in flight →
                // after one refetch every client shows the server rows; the
                // server rows are what both clients' acked ops produce.
                let quiet = s.clients.iter().enumerate().all(|(i, c)| {
                    c.outbox.is_empty()
                        && c.inflight.is_none()
                        && c.script_pos as usize == m.scripts[i].len()
                });
                !quiet
                    || s.clients
                        .iter()
                        .all(|c| c.base_rev < s.revision || c.base == s.rows)
            }),
            Property::sometimes("conflict_rebased", |_, s: &State| {
                s.clients.iter().any(|c| c.conflicts > 0)
            }),
        ]
    }
}

pub const PROTOCOL: &str = "shopping";

pub fn cases(deep: bool) -> Vec<Case> {
    use Expect::*;
    let milk = Row {
        id: RowId::Server(0),
        obj: 0,
        st: St::Needed,
        spec: false,
        rev: 0,
    };
    let seeded = RowId::Server(0);
    let own = |k| RowId::Client(9, k); // template: this client's row k
    let mut out = Vec::new();

    // S1: A adds milk with a spec (lost response), B buys milk, A buys milk.
    // A's retry carries the duplicate add next to a fresh conflicting op:
    // 409, rebase with new op ids, and the add is applied a second time.
    let s1 = Shopping {
        scripts: vec![
            vec![Kind::Add(0, own(0), true), Kind::Purchase(seeded)],
            vec![Kind::Purchase(seeded)],
        ],
        seed: vec![milk],
        drops: if deep { 2 } else { 1 },
        max_conflict_retries: 3,
        fix_dups_in_409: false,
        fix_client_row_ids: false,
    };
    out.push(Case::new(
        PROTOCOL,
        "S1 lost ack then 409 rebase (current)",
        s1.clone(),
        None,
        vec![
            ("no_duplicate_application", Violated),
            ("acked_applied_exactly_once", Violated),
            ("no_silent_drop", Holds),
            ("deleted_stays_deleted", Holds),
            ("one_active_row_per_object", Holds),
            ("clients_converge", Holds),
            ("conflict_rebased", Reached),
        ],
    ));
    out.push(Case::new(
        PROTOCOL,
        "S1 + fix: duplicates in the 409 body",
        Shopping {
            fix_dups_in_409: true,
            ..s1
        },
        None,
        vec![
            ("no_duplicate_application", Holds),
            ("acked_applied_exactly_once", Holds),
            ("no_silent_drop", Holds),
            ("deleted_stays_deleted", Holds),
            ("one_active_row_per_object", Holds),
            ("clients_converge", Holds),
            ("conflict_rebased", Reached),
        ],
    ));

    // S2: offline, A adds bread and undoes it (remove of its optimistic row);
    // one batch. The server ignores rowId, so the remove is rejected
    // (item_not_found) and the client drops it: bread stays on the list.
    let s2 = Shopping {
        scripts: vec![
            vec![Kind::Add(1, own(0), false), Kind::Remove(own(0))],
            vec![Kind::Purchase(seeded)],
        ],
        seed: vec![milk],
        drops: 1,
        max_conflict_retries: 3,
        fix_dups_in_409: true,
        fix_client_row_ids: false,
    };
    out.push(Case::new(
        PROTOCOL,
        "S2 op on an unacked optimistic row (current)",
        s2.clone(),
        None,
        vec![
            ("no_silent_drop", Violated),
            ("deleted_stays_deleted", Holds),
            ("one_active_row_per_object", Holds),
        ],
    ));
    out.push(Case::new(
        PROTOCOL,
        "S2 + fix: server keeps the client's rowId",
        Shopping {
            fix_client_row_ids: true,
            ..s2
        },
        None,
        vec![
            ("no_duplicate_application", Holds),
            ("acked_applied_exactly_once", Holds),
            ("no_silent_drop", Holds),
            ("deleted_stays_deleted", Holds),
            ("one_active_row_per_object", Holds),
            ("clients_converge", Holds),
        ],
    ));

    // S3: both fixes, two clients racing on the same object (add/remove/
    // purchase/need), lost responses: every property.
    out.push(Case::new(
        PROTOCOL,
        "S3 two clients, same object, both fixes",
        Shopping {
            scripts: vec![
                vec![
                    Kind::Add(1, own(0), true),
                    Kind::Remove(own(0)),
                    Kind::Add(1, own(1), false),
                ],
                vec![
                    Kind::Add(1, own(0), false),
                    Kind::Purchase(seeded),
                    Kind::Need(seeded),
                ],
            ],
            seed: vec![milk],
            drops: if deep { 2 } else { 1 },
            max_conflict_retries: 3,
            fix_dups_in_409: true,
            fix_client_row_ids: true,
        },
        None,
        vec![
            ("no_duplicate_application", Holds),
            ("acked_applied_exactly_once", Holds),
            ("no_silent_drop", Holds),
            ("deleted_stays_deleted", Holds),
            ("one_active_row_per_object", Holds),
            ("clients_converge", Holds),
            ("conflict_rebased", Reached),
        ],
    ));
    out
}
