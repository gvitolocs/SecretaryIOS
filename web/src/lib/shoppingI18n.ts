export function relativeTime(lang: Lang, iso: string, now = Date.now()): string {
  const t = Date.parse(iso);
  if (Number.isNaN(t)) return "";
  const min = Math.max(0, Math.round((now - t) / 60_000));
  if (min < 1) return translate(lang, "justNow");
  if (min < 60) return translate(lang, "minutesAgo", { n: min });
  const h = Math.round(min / 60);
  if (h < 24) return translate(lang, "hoursAgo", { n: h });
  return translate(lang, "daysAgo", { n: Math.round(h / 24) });
}
