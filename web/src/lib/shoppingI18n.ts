export const STRINGS: Record<Lang, Strings> = { it, en, da };

export const LANG_LABEL: Record<Lang, string> = { it: "Italiano", en: "English", da: "Dansk" };

export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  const template = STRINGS[lang][key] ?? STRINGS.it[key];
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function themeName(lang: Lang, theme: ListTheme): string {
  return STRINGS[lang].themes[theme];
}

/** Display name of a source channel ("telegram" -> "Telegram"). */
export function sourceName(src: string): string {
  const known: Record<string, string> = {
    telegram: "Telegram",
    discord: "Discord",
    web: "Web",
    ios: "iOS",
    alexa: "Alexa",
    lucina: "Lucina",
  };
  return known[src.toLowerCase()] ?? src;
}

